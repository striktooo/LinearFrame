    public static bool IsPolish { get; private set; }

    public static void Init(string setting)
    {
        IsPolish = setting switch
        {
            "pl" => true,
            "en" => false,
            _ => CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.Equals("pl", StringComparison.OrdinalIgnoreCase),
        };
    }

    public static string T(string key)
    {
        var dict = IsPolish ? Pl : En;
        if (dict.TryGetValue(key, out var v)) return v;
        if (En.TryGetValue(key, out v)) return v;
        return key;
    }

    public static string F(string key, params object[] args) => string.Format(T(key), args);

